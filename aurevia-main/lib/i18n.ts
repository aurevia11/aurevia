const translationsByLocale = Object.fromEntries(
  locales.map(locale => [
    locale,
    Object.assign({}, base, localized[locale as Exclude<Locale, "en">]),
  ]),
) as Record<Locale, TranslationMessages>;
export const translations = translationsByLocale;
export function t(
  locale: Locale,
  key: TranslationKey,
  values: Record<string, string | number> = {},
): string {
  const template = translations[locale][key] ?? translations.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) =>
    String(values[name] ?? `{${name}}`),
  );
}
